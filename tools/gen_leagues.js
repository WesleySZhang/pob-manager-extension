// Generates data/leagues.js from the PoE wiki vault's league pages (wiki/leagues/*.md: poewiki Cargo `events` rows,
// data_version "poewiki Cargo 2026-10-30"). Keeps the "Challenge league" rows: name, release version, start and end.
// Usage: node tools/gen_leagues.js [path to the PoE wiki vault]
"use strict";
const fs = require("fs");
const path = require("path");

const vault = process.argv[2] || "C:/Users/Wesley/Documents/Obsidian/PoE";
const dir = path.join(vault, "wiki", "leagues");
const out = path.join(__dirname, "..", "data", "leagues.js");

/** Parses the "League data" table rows of one page. Columns: Event | Type | Release version | Release date | End date | ... */
function challengeRows(markdown) {
  const rows = [];
  for (const line of markdown.split(/\r?\n/)) {
    const cells = line.split("|").map((c) => c.trim());
    // A row is "| a | b | ... |", so cells[0] and the last are empty.
    if (cells.length < 7 || cells[2] !== "Challenge league") continue;
    const [, event, , version, start, end] = cells;
    if (!/^\d+\.\d+\.\d+$/.test(version)) continue;
    rows.push({
      name: event.replace(/ league$/, ""),
      version: version,
      start: start ? start.replace(" ", "T") + "Z" : null,
      end: end ? end.replace(" ", "T") + "Z" : null,
    });
  }
  return rows;
}

function main() {
  const leagues = [];
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
    for (const row of challengeRows(fs.readFileSync(path.join(dir, file), "utf8"))) {
      row.page = "wiki/leagues/" + file;
      leagues.push(row);
    }
  }
  leagues.sort((a, b) => (a.start < b.start ? -1 : a.start > b.start ? 1 : 0));
  const body = JSON.stringify(leagues, null, 2).replace(/\n/g, "\n  ");
  fs.writeFileSync(out,
    "// Generated by tools/gen_leagues.js from the PoE wiki vault (wiki/leagues/*.md, poewiki Cargo events). Do not edit by hand.\n" +
    "(function (root) {\n  \"use strict\";\n  const leagues = " + body + ";\n" +
    "  if (typeof module !== \"undefined\" && module.exports) module.exports = leagues;\n  else root.PobLeagues = leagues;\n" +
    "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n");
  console.log("wrote " + path.relative(process.cwd(), out) + " (" + leagues.length + " leagues)");
}

if (require.main === module) main();
module.exports = { challengeRows };
